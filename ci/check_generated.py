import argparse
from pathlib import Path
import re
import subprocess
import sys

import yaml

ROOT = Path(__file__).resolve().parent.parent
DDL_TARGETS = (
    ("remote", "config/graph.sql"),
    ("remote-persistent", "config/graph_persistent.sql"),
    ("local", "config/graph_local.sql"),
)


def check(command, filename=None, schema_version=None):
    label = filename or " ".join(command)
    print(f"Checking {label}", flush=True)
    try:
        if filename:
            actual = (ROOT / filename).read_bytes()
            if schema_version is not None:
                header = re.search(rb"SCHEMA_VERSION=([0-9]+)", actual.partition(b"\n")[0])
                if header is None:
                    raise ValueError(f"{filename} is missing the AUTOGENERATED header.")
                version = header[1].decode("ascii")
                if version != str(schema_version):
                    raise ValueError(
                        f"{filename} header says SCHEMA_VERSION={version} but "
                        f"config/versions.yaml pins schema: {schema_version}."
                    )

        result = subprocess.run(command, cwd=ROOT, stdout=subprocess.PIPE if filename else None)
        if result.returncode:
            raise ValueError(f"{' '.join(command)} failed (exit {result.returncode}).")
        if filename:
            generated = result.stdout
            if schema_version is not None:
                actual, generated = actual.rstrip(b"\n"), generated.rstrip(b"\n")
            if actual != generated:
                task = "schema:generate:ddl" if schema_version is not None else "schema:generate"
                raise ValueError(f"{filename} is out of date. Run: mise {task}")
            print(f"{filename} is up to date.")
        return 0
    except (OSError, ValueError) as error:
        print(f"ERROR: {label}: {error}", file=sys.stderr)
        return 1


def main():
    parser = argparse.ArgumentParser(description="Check generated files without rewriting them.")
    parser.add_argument("selection", nargs="?", default="all", choices=("all", "ddl"))
    args = parser.parse_args()
    status = 0
    if args.selection == "all":
        status |= check(["cargo", "xtask", "schema"], "config/schemas/config.schema.json")
        status |= check(["cargo", "xtask", "metrics-catalog", "--check"])
        status |= check([sys.executable, "ci/dashboards.py", "--check"])
        status |= check(["cargo", "xtask", "query-docs", "--check"])

    try:
        schema_version = yaml.safe_load((ROOT / "config/versions.yaml").read_bytes())["schema"]
        if type(schema_version) is not int or schema_version < 0:
            raise ValueError("schema must be a non-negative integer")
    except (OSError, ValueError, KeyError, TypeError, yaml.YAMLError) as error:
        print(f"ERROR: config/versions.yaml: {error}", file=sys.stderr)
        return 1

    for target, filename in DDL_TARGETS:
        status |= check(["cargo", "xtask", "ddl", "--target", target], filename, schema_version)
    return status


if __name__ == "__main__":
    sys.exit(main())
