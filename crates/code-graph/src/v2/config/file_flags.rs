use std::sync::LazyLock;

use globset::{Glob, GlobSet, GlobSetBuilder};
use serde::Deserialize;

const FILE_FLAGS_YAML: &str = include_str!("../../../../../config/code-graph-file-flags.yaml");
const MARKER_WINDOW: usize = 1024;

#[derive(Deserialize)]
struct FlagConfig {
    test: FlagRule,
    generated: FlagRule,
    vendored: FlagRule,
}

#[derive(Deserialize, Default)]
struct FlagRule {
    #[serde(default)]
    globs: Vec<String>,
    #[serde(default)]
    markers: Vec<String>,
}

struct CompiledFlags {
    test: GlobSet,
    generated: GlobSet,
    vendored: GlobSet,
    generated_markers: Vec<String>,
}

fn compile(globs: &[String]) -> GlobSet {
    let mut builder = GlobSetBuilder::new();
    for pattern in globs {
        builder
            .add(Glob::new(pattern).expect("file flag glob in config/code-graph-file-flags.yaml"));
    }
    builder.build().expect("file flag globset")
}

static FLAGS: LazyLock<CompiledFlags> = LazyLock::new(|| {
    let config: FlagConfig =
        orbit_utils::yaml::from_str(FILE_FLAGS_YAML).expect("config/code-graph-file-flags.yaml");
    CompiledFlags {
        test: compile(&config.test.globs),
        generated: compile(&config.generated.globs),
        vendored: compile(&config.vendored.globs),
        generated_markers: config.generated.markers,
    }
});

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct FileFlags {
    pub is_test: bool,
    pub is_generated: bool,
    pub is_vendored: bool,
}

pub fn path_flags(path: &str) -> FileFlags {
    let flags = &*FLAGS;
    FileFlags {
        is_test: flags.test.is_match(path),
        is_generated: flags.generated.is_match(path),
        is_vendored: flags.vendored.is_match(path),
    }
}

pub fn has_generated_marker(content: &[u8]) -> bool {
    let window = &content[..content.len().min(MARKER_WINDOW)];
    let text = String::from_utf8_lossy(window);
    FLAGS
        .generated_markers
        .iter()
        .any(|marker| text.contains(marker.as_str()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn config_compiles() {
        assert!(path_flags("src/app/models/user_test.go").is_test);
        assert!(path_flags("vendor/github.com/x/y.go").is_vendored);
        assert!(path_flags("api/user.pb.go").is_generated);
        assert_eq!(path_flags("src/app.py"), FileFlags::default());
        assert!(has_generated_marker(
            b"// Code generated by protoc. DO NOT EDIT.\npackage x"
        ));
    }
}
