use query_data_model::storage::{LocalType, StorageType, TableLayout};

fn emit_column_type(data_type: &LocalType) -> String {
    match data_type {
        LocalType::Int64 => "BIGINT".into(),
        LocalType::UInt64 => "UBIGINT".into(),
        LocalType::Bool => "BOOLEAN".into(),
        LocalType::String => "VARCHAR".into(),
        LocalType::Date => "DATE".into(),
        LocalType::Timestamp => "TIMESTAMP".into(),
        LocalType::Nullable(inner) => emit_column_type(inner),
        LocalType::Array(inner) => format!("{}[]", emit_column_type(inner)),
    }
}

pub fn generate_local_ddl(
    ontology: &ontology::Ontology,
    external_ddl: &str,
) -> Result<String, query_data_model::DataModelError> {
    let schema_version = orbit_versions::VERSIONS.schema;
    let mut ddl = format!(
        "-- SCHEMA_VERSION={schema_version} [AUTOGENERATED — DO NOT EDIT MANUALLY]\n\
         -- Regenerate with: mise schema:generate:ddl\n\
         \n{external_ddl}\n\n"
    );
    for table in super::generate_local_tables(ontology)? {
        ddl.push_str(&format!("{};\n\n", emit_create_table(&table)));
    }
    ddl.push('\n');
    Ok(ddl)
}

pub fn emit_create_table(table: &TableLayout) -> String {
    let columns = table
        .columns
        .iter()
        .map(|column| {
            let StorageType::DuckDb(data_type) = &column.data_type else {
                panic!("local DDL requires a DuckDB table schema");
            };
            let nullable = matches!(data_type, LocalType::Nullable(_));
            let mut sql = format!(
                "    {} {}{}",
                column.name,
                emit_column_type(data_type),
                if nullable { "" } else { " NOT NULL" }
            );
            if let Some(default) = &column.default {
                sql.push_str(&format!(" DEFAULT {default}"));
            }
            sql
        })
        .collect::<Vec<_>>();
    format!(
        "CREATE TABLE IF NOT EXISTS {} (\n{}\n)",
        table.name,
        columns.join(",\n")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn local_ddl_matches_committed_storage() {
        let ontology = ontology::Ontology::load_embedded().unwrap();
        let committed = include_str!("../../../../../../../config/graph_local.sql");
        let tables = super::super::generate_local_tables(&ontology).unwrap();
        assert_eq!(tables.len(), 5);
        for table in tables {
            let sql = emit_create_table(&table);
            assert!(
                committed.contains(&sql),
                "{} differs from committed DDL:\n{sql}",
                table.name
            );
        }
    }

    #[test]
    fn local_storage_preserves_nullable_wrappers_arrays_and_literal_defaults() {
        let mut node = ontology::NodeEntity {
            destination_table: "values".into(),
            ..Default::default()
        };
        node.storage.columns = [
            ("id", "Int64", None),
            ("optional", "LowCardinality(Nullable(String))", None),
            ("tags", "Array(LowCardinality(String))", None),
            ("time", "Nullable(DateTime64(6, 'UTC'))", Some("now64(6)")),
            ("name", "String", Some("''")),
            ("deleted", "Bool", Some("false")),
        ]
        .into_iter()
        .map(|(name, ch_type, default)| ontology::StorageColumn {
            name: name.into(),
            ch_type: ch_type.into(),
            default: default.map(str::to_owned),
            codec: Some(vec!["ZSTD(1)".into()]),
        })
        .collect();
        let table = TableLayout::local_node(&node, &[]).unwrap();
        assert_eq!(
            emit_create_table(&table),
            "CREATE TABLE IF NOT EXISTS values (\n    id BIGINT NOT NULL,\n    optional VARCHAR,\n    tags VARCHAR[] NOT NULL,\n    time TIMESTAMP,\n    name VARCHAR NOT NULL DEFAULT '',\n    deleted BOOLEAN NOT NULL DEFAULT false\n)"
        );
    }
}
