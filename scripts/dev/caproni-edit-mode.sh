#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SELF="$SCRIPT_DIR/$(basename "${BASH_SOURCE[0]}")"
POD_CONFIG="${ORBIT_POD_CONFIG:-/app/config/config.yaml}"
GENERATED_DIR="${GENERATED_DIR_OVERRIDE:-$REPO_ROOT/.dev}"
BINARY="${ORBIT_BINARY_OVERRIDE:-$REPO_ROOT/target/debug/gkg-server}"
STAMP="$GENERATED_DIR/gkg-server.built"
WATCH_LOCK="$GENERATED_DIR/gkg-build.pid"

WATCH_ARGS=(--ignore-nothing --on-busy-update=queue -d 500ms -w crates -w config -w Cargo.toml -w Cargo.lock)

usage() {
  printf 'Usage: %s {build|watch|webserver|indexer-sdlc|indexer-code|dispatcher}\n' "$(basename "$0")" >&2
}

edit_mode_for() {
  case "$1" in
    webserver) echo webserver ;;
    indexer-sdlc | indexer-code) echo indexer ;;
    dispatcher) echo dispatch-indexing ;;
    *) return 1 ;;
  esac
}

probe_port_for() {
  case "$1" in
    webserver) echo 9394 ;;
    indexer-sdlc) echo 9395 ;;
    indexer-code) echo 9396 ;;
    dispatcher) echo 9397 ;;
    *) return 1 ;;
  esac
}

write_overlay() {
  local key="$1" port target tmp
  port="$(probe_port_for "$key")"
  target="$GENERATED_DIR/caproni-$key.yaml"
  mkdir -p "$GENERATED_DIR"
  tmp="$(mktemp "$target.XXXXXX")"
  echo "# Generated by scripts/dev/caproni-edit-mode.sh from the pod's $POD_CONFIG; regenerated on every start." >"$tmp"
  if ! cat "$POD_CONFIG" | yq ".probe_server.bind_address = \"0.0.0.0:$port\" | del(.metrics.prometheus.port)" >>"$tmp"; then
    rm -f "$tmp"
    printf 'ERROR: could not rewrite %s; see the error above\n' "$POD_CONFIG" >&2
    return 1
  fi
  chmod 600 "$tmp"
  mv "$tmp" "$target"
  echo "$target"
}

cargo_build() {
  (cd "$REPO_ROOT" && mise exec -- cargo build --bin gkg-server --message-format=json-render-diagnostics)
}

artifact_identity() {
  local artifact
  artifact="$(yq -p json -o json -r 'select(.reason == "compiler-artifact" and .target.name == "gkg-server") | .filenames[0]' "$1" 2>/dev/null | tail -1)"
  [[ -n "$artifact" && -e "$artifact" ]] || return 1
  stat -c '%s:%Y' "$artifact" 2>/dev/null || stat -f '%z:%m' "$artifact"
}

build() {
  local msgs identity
  mkdir -p "$GENERATED_DIR"
  msgs="$(mktemp "$GENERATED_DIR/cargo-messages.XXXXXX")"
  if ! cargo_build >"$msgs"; then
    rm -f "$msgs"
    return 1
  fi
  identity="$(artifact_identity "$msgs")" || identity="unknown-$(date +%s)"
  rm -f "$msgs"
  if [[ "$(cat "$STAMP" 2>/dev/null)" != "$identity" ]]; then
    printf '%s\n' "$identity" >"$STAMP"
  fi
}

process_command() {
  if [[ -r "/proc/$1/cmdline" ]]; then
    tr '\0' ' ' 2>/dev/null <"/proc/$1/cmdline"
  else
    ps -o command= -p "$1" 2>/dev/null
  fi
}

lock_holder_alive() {
  kill -0 "$1" 2>/dev/null && process_command "$1" | grep -qE 'watchexec|caproni-edit-mode'
}

claim_lock() {
  local lock="$1" holder
  if (set -o noclobber; echo "$$" >"$lock") 2>/dev/null; then
    return 0
  fi
  holder="$(cat "$lock" 2>/dev/null || true)"
  if [[ -z "$holder" ]] || lock_holder_alive "$holder"; then
    return 1
  fi
  replace_stale_lock "$lock" "$holder"
}

replace_stale_lock() {
  local lock="$1" holder="$2" claim="$1.stale.$2" status=1
  claim_lock "$claim" || return 1
  if [[ "$(cat "$lock" 2>/dev/null || true)" == "$holder" ]]; then
    rm -f "$lock"
    (set -o noclobber; echo "$$" >"$lock") 2>/dev/null && status=0
  fi
  rm -f "$claim"
  return "$status"
}

acquire_watch_lock() {
  mkdir -p "$GENERATED_DIR"
  claim_lock "$WATCH_LOCK"
}

watch() {
  if ! acquire_watch_lock; then
    echo "another gkg-build watcher owns $WATCH_LOCK; this one idles"
    exec sleep 2147483647
  fi
  cd "$REPO_ROOT"
  exec mise exec -- watchexec --shell=none "${WATCH_ARGS[@]}" -- "$SELF" build
}

library_path() {
  # shellcheck disable=SC2012
  ls -td "$(dirname "$BINARY")"/build/aws-lc-fips-sys/*/out/build/artifacts 2>/dev/null | paste -sd: - || true
}

launch() {
  local libs
  libs="$(library_path)"
  if [[ -n "$libs" ]]; then
    export DYLD_FALLBACK_LIBRARY_PATH="${libs}${DYLD_FALLBACK_LIBRARY_PATH:+:$DYLD_FALLBACK_LIBRARY_PATH}"
    export LD_LIBRARY_PATH="${libs}${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
  fi
  exec "$BINARY" --mode="$1" --config="$2"
}

run_mode() {
  local key="$1" mode overlay
  mode="$(edit_mode_for "$key")"
  if [[ ! -r "$POD_CONFIG" ]]; then
    cat >&2 <<EOF
ERROR: $POD_CONFIG is not readable.

This script runs under \`caproni run\`, where mirrord serves that file from the
Orbit pod. Start it from your gitlab-caproni checkout with the knowledge-graph
reloaders enabled in caproni.local.yaml; see docs/pages/engineering/development/local-development.md.
EOF
    exit 1
  fi
  overlay="$(write_overlay "$key")"
  if [[ ! -s "$STAMP" ]]; then
    echo "waiting for the first build; gkg-build writes $STAMP when gkg-server is ready"
    while [[ ! -s "$STAMP" ]]; do sleep 2; done
  fi
  cd "$REPO_ROOT"
  exec mise exec -- watchexec --shell=none --ignore-nothing -r -d 1s -w "$STAMP" -- "$SELF" launch "$mode" "$overlay"
}

main() {
  case "${1:-}" in
    build) build ;;
    watch) watch ;;
    launch) [[ $# -eq 3 ]] || { usage; exit 1; }; launch "$2" "$3" ;;
    webserver | indexer-sdlc | indexer-code | dispatcher) run_mode "$1" ;;
    *) usage; exit 1 ;;
  esac
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
