#!/usr/bin/env bash
# Runs one Orbit mode on the host inside a Caproni edit-mode (mirrord) session.
#
# Usage: scripts/dev/caproni-edit-mode.sh {webserver|indexer-sdlc|indexer-code|dispatcher}
#
# The reloaders in caproni-project.yaml start this script under `mirrord exec`
# targeting the matching Orbit pod. The reloader marks /app/config and
# /etc/secrets read-only, so mirrord serves both from the pod and gkg-server
# runs with the pod's own configuration. The one change is the probe server
# port: every pod binds the chart's single probeServer.port (9394) and four
# host processes cannot share it. The webserver keeps 9394 because mirrord
# steals the pod's readiness probes to the local listener; the others move.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
POD_CONFIG="${ORBIT_POD_CONFIG:-/app/config/config.yaml}"
GENERATED_DIR="${GENERATED_DIR_OVERRIDE:-$REPO_ROOT/.dev}"

usage() {
  printf 'Usage: %s {webserver|indexer-sdlc|indexer-code|dispatcher}\n' "$(basename "$0")" >&2
}

# Reloader key -> gkg-server --mode.
edit_mode_for() {
  case "$1" in
    webserver) echo webserver ;;
    indexer-sdlc | indexer-code) echo indexer ;;
    dispatcher) echo dispatch-indexing ;;
    *) return 1 ;;
  esac
}

# Reloader key -> host-side probe server port.
probe_port_for() {
  case "$1" in
    webserver) echo 9394 ;;
    indexer-sdlc) echo 9395 ;;
    indexer-code) echo 9396 ;;
    dispatcher) echo 9397 ;;
    *) return 1 ;;
  esac
}

# Copies the pod config with the probe port replaced; prints the path. The deprecated
# metrics.prometheus.port key goes too: the server refuses a config where it disagrees
# with probe_server.bind_address, and the probe server serves /-/metrics anyway.
# yq's status is checked explicitly because callers run this inside $(...), where
# errexit does not apply on bash 3.2.
write_overlay() {
  local key="$1" port target tmp
  port="$(probe_port_for "$key")"
  target="$GENERATED_DIR/caproni-$key.yaml"
  mkdir -p "$GENERATED_DIR"
  tmp="$(mktemp "$target.XXXXXX")"
  echo "# Generated by scripts/dev/caproni-edit-mode.sh from the pod's $POD_CONFIG; regenerated on every start." >"$tmp"
  if ! yq ".probe_server.bind_address = \"0.0.0.0:$port\" | del(.metrics.prometheus.port)" "$POD_CONFIG" >>"$tmp"; then
    rm -f "$tmp"
    printf 'ERROR: could not rewrite %s; see the yq error above\n' "$POD_CONFIG" >&2
    return 1
  fi
  chmod 600 "$tmp"
  mv "$tmp" "$target"
  echo "$target"
}

main() {
  local key="${1:-}" mode overlay
  mode="$(edit_mode_for "$key")" || { usage; exit 1; }
  if [[ ! -r "$POD_CONFIG" ]]; then
    cat >&2 <<EOF
ERROR: $POD_CONFIG is not readable.

This script runs under \`caproni run\`, where mirrord serves that file from the
Orbit pod. Start it from your gitlab-caproni checkout with the knowledge-graph
reloaders enabled in caproni.local.yaml; see docs/dev/local-development.md.
EOF
    exit 1
  fi
  overlay="$(write_overlay "$key")"
  cd "$REPO_ROOT"
  # mise resolves cargo and cargo-watch from this repo's mise.toml regardless of
  # the PATH caproni inherited from the gitlab-caproni checkout.
  exec mise exec -- cargo watch --why -x "run --bin gkg-server -- --mode=$mode --config=$overlay"
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
