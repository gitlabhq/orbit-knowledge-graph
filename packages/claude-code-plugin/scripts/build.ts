// A hooks module may import only its own files by relative path, and claude-code. So the build
// copies the plugin with @orbit/agent-plugin-core under hooks/core/, imports made relative, and the
// call labels written out as hooks/core/labels.ts. dist/ holds the plugin and its tests for
// `claude plugin test`. The plugin without tests goes where `orbit setup --claude-ui` installs
// from; CI rebuilds it and fails on a diff.
import { cp, mkdir, readdir, rm } from 'node:fs/promises'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
const core = join(root, '../agent-plugin-core/src')
const labels = join(root, '../../config/setup/call_labels.yaml')
const dist = join(root, 'dist')
const shipped = join(root, '../../config/setup/claude_plugin/gitlab-orbit')
const HEADER = '// Generated by packages/claude-code-plugin/scripts/build.ts. Do not edit.\n'

async function copySources(from: string, to: string, rewrite: (text: string) => string): Promise<void> {
  await mkdir(to, { recursive: true })
  for (const name of await readdir(from)) {
    if (!name.endsWith('.ts') || name.endsWith('.d.ts')) continue
    await Bun.write(join(to, name), HEADER + rewrite(await Bun.file(join(from, name)).text()))
  }
}

function importCore(index: string): (text: string) => string {
  return (text) => text.replaceAll("from '@orbit/agent-plugin-core'", "from '" + index + "'")
}

await rm(dist, { recursive: true, force: true })
await copySources(join(root, 'hooks'), join(dist, 'hooks'), importCore('./core/index.ts'))
await copySources(join(root, 'tests'), join(dist, 'tests'), importCore('../hooks/core/index.ts'))
await copySources(core, join(dist, 'hooks/core'), (text) =>
  text.replace(/from '[./]+config\/setup\/call_labels\.yaml'/, "from './labels.ts'"),
)
const table: unknown = Bun.YAML.parse(await Bun.file(labels).text())
await Bun.write(join(dist, 'hooks/core/labels.ts'), HEADER + 'export default ' + JSON.stringify(table, null, 2) + '\n')
await cp(join(root, 'hooks/hooks.json'), join(dist, 'hooks/hooks.json'))
await cp(join(root, '.claude-plugin/plugin.json'), join(dist, '.claude-plugin/plugin.json'))

await rm(shipped, { recursive: true, force: true })
await cp(dist, shipped, { recursive: true, filter: (path) => !path.startsWith(join(dist, 'tests')) })
