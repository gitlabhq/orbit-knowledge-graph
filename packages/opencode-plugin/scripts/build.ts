// Bundles the plugin, with @orbit/agent-plugin-core and the call labels inlined, into the one
// file `orbit setup` installs for OpenCode. CI rebuilds it and fails on a diff.
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
const out = join(root, '../../config/setup/opencode_plugin.js')

const result = await Bun.build({ entrypoints: [join(root, 'src/index.ts')], target: 'bun', format: 'esm' })
const [bundle] = result.outputs
if (!result.success || !bundle) throw new AggregateError(result.logs, 'opencode-plugin build failed')
await Bun.write(out, '// Generated by packages/opencode-plugin/scripts/build.ts. Do not edit.\n' + (await bundle.text()))
